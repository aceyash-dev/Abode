#!/usr/bin/env python3
"""
Generates ui-keyboard/.../EmojiCatalog.kt from the emojibase dataset.

Usage:
    npm pack emojibase-data@18.0.0 && tar xzf emojibase-data-18.0.0.tgz
    python3 tools/make_emoji.py package/en/data.json

Only fully-qualified base emoji are kept, and only those in Unicode 16.0 or
earlier, so the keyboard never offers a character the system font predates.
Skin-tone modifiers (group 2) are left out; they belong on a long press, not
in the grid.
"""
import json
import sys
from pathlib import Path

MAX_VERSION = 16.0

# emojibase group id -> (display name, tab glyph)
CATEGORIES = [
    (0, "Smileys", "\U0001F600"),
    (1, "People", "\U0001F44B"),
    (3, "Animals", "\U0001F436"),
    (4, "Food", "\U0001F34E"),
    (5, "Travel", "✈️"),
    (6, "Activities", "⚽"),
    (7, "Objects", "\U0001F4A1"),
    (8, "Symbols", "\U0001F523"),
    (9, "Flags", "\U0001F3C1"),
]

OUT = Path(__file__).resolve().parent.parent / (
    "ui-keyboard/src/main/kotlin/dev/abode/keyboard/EmojiCatalog.kt"
)


def kotlin_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def main() -> None:
    data = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    groups = {g: [] for g, _, _ in CATEGORIES}
    for entry in data:
        group = entry.get("group")
        if group not in groups:
            continue
        if entry.get("type") != 1 or float(entry.get("version", 0)) > MAX_VERSION:
            continue
        groups[group].append((entry.get("order", 0), entry["emoji"]))

    lines = [
        "// Generated by tools/make_emoji.py from emojibase-data. Do not edit by hand.",
        "// Unicode 16.0: fully-qualified base emoji only.",
        "package dev.abode.keyboard",
        "",
        "/** One tab of the emoji page: its name, the glyph on its tab, and its emoji in order. */",
        "class EmojiCategory(val name: String, val tabGlyph: String, val emoji: List<String>)",
        "",
        "object EmojiCatalog {",
    ]
    for index, (group, name, glyph) in enumerate(CATEGORIES):
        ordered = [e for _, e in sorted(groups[group], key=lambda pair: pair[0])]
        lines.append(f"    private const val CATEGORY_{index} =")
        lines.append("        " + kotlin_string(" ".join(ordered)))
        lines.append("")
    lines.append("    val categories: List<EmojiCategory> = listOf(")
    for index, (_, name, glyph) in enumerate(CATEGORIES):
        lines.append(
            f"        EmojiCategory({kotlin_string(name)}, {kotlin_string(glyph)}, "
            f"CATEGORY_{index}.split(\" \")),"
        )
    lines.append("    )")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    total = sum(len(v) for v in groups.values())
    print(f"wrote {OUT} with {total} emoji")


if __name__ == "__main__":
    main()
